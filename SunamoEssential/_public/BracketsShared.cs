namespace SunamoEssential._public;

/// <summary>
/// Represents the brackets shared type.
/// </summary>
public enum BracketsShared
{
    // Curly brackets: { }
    /// <summary>
    /// The curly value.
    /// </summary>
    Curly,
    // Square brackets: [ ]
    /// <summary>
    /// The square value.
    /// </summary>
    Square,
    /// <summary>
    /// The normal value.
    /// </summary>
    Normal,
    // No brackets.
    /// <summary>
    /// The none value.
    /// </summary>
    None
}
